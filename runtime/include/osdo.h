const osdo_method_def *osdo_method_info(const osdo_class *cls, const char *method);
int osdo_method_slot(const osdo_class *cls, const char *method);   /* -1 if none */

/* --------------------------------------------------------------- pending
 * The result of an asynchronous method. Loop thread only. */
typedef void (*osdo_pending_cb)(osdo_pending *p, const osdo_value *v, void *user);

osdo_pending *osdo_pending_new(void);
osdo_pending *osdo_pending_ref(osdo_pending *p);
